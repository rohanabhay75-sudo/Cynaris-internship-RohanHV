-- AGGREGATE FUNCTIONS
-- COUNT
SELECT COUNT(*) AS TOTAL_SALES FROM SALES;
-- SUM
SELECT SUM(AMOUNT) AS TOTAL_REVENUE FROM SALES;
-- AVG
SELECT AVG(AMOUNT) AS AVG_REVENUE FROM SALES;
-- MAX
SELECT MAX(AMOUNT) AS HIGHEST_SALES FROM SALES;
-- MIN
SELECT MIN(AMOUNT) AS LOWEST_SALES FROM SALES;
-- GROUP BY REGION
SELECT REGION ,SUM(AMOUNT) AS REVENUE FROM SALES GROUP BY REGION;
-- GROUP BY CATEGORY
SELECT CATEGORY, COUNT(*) AS TOTAL_ORDERS FROM SALES GROUP BY CATEGORY;
-- HAVING
SELECT REGION, SUM(AMOUNT) AS REVENUE FROM SALES GROUP BY REGION HAVING SUM(AMOUNT)>10000;
-- GROUP SALES BY REGION CATEGORY AND MONTH
SELECT REGION,CATEGORY, MOUNT(SALE_DATE) AS SALE_MONTH,SUM(AMOUNT) AS TOTAL_SALES
FROM SALES GROUP BY REGION, CATEGORY,MONTH(SALE_DATE);
-- WINDOW FUNCTION
SELECT SALE_ID,AMOUNT,REGION,SUM(AMOUNT) OVER() AS OVERALL_SALES FROM SALES;